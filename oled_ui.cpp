void showControllerInfo(ControllerPtr ctl) {
    display.clearDisplay();
    display.setTextSize(1);
    display.setTextColor(SSD1306_WHITE);

    int16_t x, z;
    uint16_t w, h;
    display.getTextBounds("Eixos e Gatilhos", 0, 0, &x, &z, &w, &h);
    display.setCursor((SCREEN_WIDTH - w) / 2, 2);
    display.println("Eixos e Gatilhos");

    int y = 14;
    const int lineHeight = 8;

    display.setCursor(0, y);
    display.print("LX:"); 
    drawProgressBar(24, y, 100, 6, ctl->axisX() + 512, 1023);
    y += lineHeight;

    display.setCursor(0, y);
    display.print("LY:");
    drawProgressBar(24, y, 100, 6, ctl->axisY() + 512, 1023);
    y += lineHeight;

    display.setCursor(0, y);
    display.print("RX:");
    drawProgressBar(24, y, 100, 6, ctl->axisRX() + 512, 1023);
    y += lineHeight;

    display.setCursor(0, y);
    display.print("RY:");
    drawProgressBar(24, y, 100, 6, ctl->axisRY() + 512, 1023);
    y += lineHeight;

    display.setCursor(0, y);
    display.print("LT:");
    drawProgressBar(24, y, 100, 6, ctl->brake(), 1023);
    y += lineHeight;

    display.setCursor(0, y);
    display.print("RT:");
    drawProgressBar(24, y, 100, 6, ctl->throttle(), 1023);

    display.display();
}

